"""
Formal Verification of Structural XOR Reachability in sampleLogicalPerms.
"""

def pair_at(n, i):
    d = n - 1
    a = i // d
    j = i % d
    b = j if j < a else j + 1
    return a, b

def get_args(op, n, picked, labels):
    perms = []
    for i in picked:
        a, b = pair_at(n, i)
        var_a = labels[a]
        var_b = labels[b]
        if b < a:
            perms.append((op, var_b, var_a))
        else:
            perms.append((op, f"(NOT {var_a})", var_b))
    return perms

def main():
    labels = ["X1", "X2", "X3", "X4"]
    n = len(labels)
    total_pairs = n * (n - 1)
    
    print(f"Total pair indices for n={n}: {total_pairs}")
    
    all_possible_clauses = set()
    for i in range(total_pairs):
        a, b = pair_at(n, i)
        var_a = labels[a]
        var_b = labels[b]
        if b < a:
            clause = f"(AND {var_b} {var_a})"
        else:
            clause = f"(AND (NOT {var_a}) {var_b})"
        all_possible_clauses.add(clause)
        print(f"Index {i:2d}: pair=({a}, {b}) -> vars=({var_a}, {var_b}) -> clause: {clause}")
        
    print("\n" + "=" * 60)
    print("TOTAL DISTINCT CLAUSES EVER GENERATED BY sampleLogicalPerms:")
    print("=" * 60)
    for c in sorted(all_possible_clauses):
        print(" ", c)
        
    print("\n" + "=" * 60)
    print("CHECKING XOR BUILDING BLOCKS:")
    print("=" * 60)
    xor_required = [
        # X1 ^ X2
        ("(AND (NOT X1) X2)", "(AND X1 (NOT X2))"),
        # X3 ^ X4
        ("(AND (NOT X3) X4)", "(AND X3 (NOT X4))"),
        # Other pairs
        ("(AND (NOT X1) X3)", "(AND X1 (NOT X3))"),
        ("(AND (NOT X1) X4)", "(AND X1 (NOT X4))"),
        ("(AND (NOT X2) X3)", "(AND X2 (NOT X3))"),
        ("(AND (NOT X2) X4)", "(AND X2 (NOT X4))"),
    ]
    
    for c1, c2 in xor_required:
        in1 = c1 in all_possible_clauses
        in2 = c2 in all_possible_clauses
        print(f"Pair: {c1:22s} [Present: {str(in1):5s}] | {c2:22s} [Present: {str(in2):5s}]")
        
    print("\nDouble negative clauses (e.g. (AND (NOT X1) (NOT X2))):")
    double_negs = [c for c in all_possible_clauses if c.count("NOT") == 2]
    print(f"Count generated: {len(double_negs)}")

if __name__ == "__main__":
    main()
